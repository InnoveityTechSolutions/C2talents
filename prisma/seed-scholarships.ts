export async function seed100Scholarships() {
  console.log(`🌱 [SEED] Seeding ${REAL_SCHOLARSHIPS_100.length} Verified Real Scholarships into MySQL...`);
  let inserted = 0;
  let updated = 0;

  for (const s of REAL_SCHOLARSHIPS_100) {
    const existing = await db.scholarship.findFirst({
      where: { name: s.name },
    });

    if (!existing) {
      await db.scholarship.create({
        data: {
          name: s.name,
          provider: s.provider,
          category: s.category,
          scholarshipType: s.scholarshipType,
          description: s.description,
          eligibilityCriteria: s.eligibilityCriteria,
          minPercentage: s.minPercentage || null,
          eligibleCourses: s.eligibleCourses,
          eligibleStates: s.eligibleStates,
          familyIncomeLimit: s.familyIncomeLimit || null,
          familyIncomeLimitText: s.familyIncomeLimitText || null,
          amount: s.amount,
          amountValue: s.amountValue || null,
          deadline: s.deadline || "December 31, 2026",
          deadlineDate: s.deadlineDate || new Date("2026-12-31T23:59:59Z"),
          officialWebsite: s.officialWebsite,
          applyLink: s.applyLink,
          requiredDocuments: s.requiredDocuments,
          selectionProcess: s.selectionProcess || "Merit and financial document scrutiny",
          renewalAvailable: s.renewalAvailable,
          status: s.status,
          isPublished: s.isPublished,
          isFeatured: s.isFeatured,
          faqs: s.faqs || null,
        },
      });
      inserted++;
    } else {
      await db.scholarship.update({
        where: { id: existing.id },
        data: {
          provider: s.provider,
          category: s.category,
          scholarshipType: s.scholarshipType,
          description: s.description,
          eligibilityCriteria: s.eligibilityCriteria,
          minPercentage: s.minPercentage || null,
          eligibleCourses: s.eligibleCourses,
          eligibleStates: s.eligibleStates,
          familyIncomeLimit: s.familyIncomeLimit || null,
          familyIncomeLimitText: s.familyIncomeLimitText || null,
          amount: s.amount,
          officialWebsite: s.officialWebsite,
          applyLink: s.applyLink,
          requiredDocuments: s.requiredDocuments,
          isPublished: true,
        },
      });
      updated++;
    }
  }

  console.log(`✅ [SEED] Complete. Inserted: ${inserted} | Updated: ${updated}`);
  return inserted + updated;
}

